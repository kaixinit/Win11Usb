"""Convert the published beta.3 Geometry paths to native GDI+ cubic paths.

Development-only, standard-library generator; the generated header is checked in.
The EXE does not load XAML, Python, fonts or external image files for these icons.
Paths retain their Apache-2.0 provenance in third_party/material-design-icons.
"""
import math
import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NS = '{http://schemas.microsoft.com/winfx/2006/xaml/presentation}'
KEY = '{http://schemas.microsoft.com/winfx/2006/xaml}Key'


def arc(x, y, rx, ry, angle, large, sweep, ex, ey):
    rx, ry = abs(rx), abs(ry)
    if not rx or not ry or (x == ex and y == ey):
        return []
    phi = math.radians(angle)
    c, s = math.cos(phi), math.sin(phi)
    xp, yp = c * (x-ex)/2 + s * (y-ey)/2, -s * (x-ex)/2 + c * (y-ey)/2
    q = xp*xp/(rx*rx) + yp*yp/(ry*ry)
    if q > 1:
        rx, ry = rx*math.sqrt(q), ry*math.sqrt(q)
    q = max(0, (rx*rx*ry*ry-rx*rx*yp*yp-ry*ry*xp*xp) /
            (rx*rx*yp*yp+ry*ry*xp*xp))
    k = (-1 if bool(large) == bool(sweep) else 1) * math.sqrt(q)
    cxp, cyp = k*rx*yp/ry, -k*ry*xp/rx
    cx, cy = c*cxp-s*cyp+(x+ex)/2, s*cxp+c*cyp+(y+ey)/2
    a = math.atan2((yp-cyp)/ry, (xp-cxp)/rx)
    end = math.atan2((-yp-cyp)/ry, (-xp-cxp)/rx)
    delta = (end-a) % (2*math.pi)
    if not sweep:
        delta = delta-2*math.pi if delta else 0
    count = max(1, math.ceil(abs(delta)/(math.pi/2)))
    points = []
    def point(t):
        return cx+rx*c*math.cos(t)-ry*s*math.sin(t), cy+rx*s*math.cos(t)+ry*c*math.sin(t)
    def tangent(t):
        return -rx*c*math.sin(t)-ry*s*math.cos(t), -rx*s*math.sin(t)+ry*c*math.cos(t)
    for i in range(count):
        b = a + delta/count
        alpha = 4/3*math.tan((b-a)/4)
        p, d, e, f = point(a), tangent(a), point(b), tangent(b)
        points.append((p[0]+alpha*d[0], p[1]+alpha*d[1],
                       e[0]-alpha*f[0], e[1]-alpha*f[1], *e))
        a = b
    return points


def convert(path):
    tokens = re.findall(r'[A-Za-z]|[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?', path)
    if tokens[:2] == ['F', '1']:
        tokens = tokens[2:]
    i, cmd, x, y, startx, starty, ctrl = 0, '', 0, 0, 0, 0, None
    result = []
    def num():
        nonlocal i
        n = float(tokens[i]); i += 1
        return n
    def f(n):
        value = f'{n:.6f}'.rstrip('0').rstrip('.')
        return value + ('.0' if '.' not in value else '') + 'f'
    def bezier(vals):
        nonlocal x, y, ctrl
        result.append('p.AddBezier(' + ','.join(map(f, (x, y, *vals))) + ');')
        ctrl, (x, y) = vals[2:4], vals[4:6]
    def line(ex, ey):
        nonlocal x, y, ctrl
        result.append('p.AddLine(' + ','.join(map(f, (x, y, ex, ey))) + ');')
        x, y, ctrl = ex, ey, None
    while i < len(tokens):
        if tokens[i].isalpha():
            cmd = tokens[i]; i += 1
        if cmd == 'M':
            x, y = num(), num(); startx, starty = x, y
            result.append('p.StartFigure();'); ctrl = None; cmd = 'L'
        elif cmd == 'L': line(num(), num())
        elif cmd == 'H': line(num(), y)
        elif cmd == 'V': line(x, num())
        elif cmd == 'C': bezier(tuple(num() for _ in range(6)))
        elif cmd == 'S':
            cx, cy = (2*x-ctrl[0], 2*y-ctrl[1]) if ctrl else (x, y)
            bezier((cx, cy, *(num() for _ in range(4))))
        elif cmd == 'A':
            rx, ry, a, large, sweep, ex, ey = (num() for _ in range(7))
            curves = arc(x, y, rx, ry, a, large, sweep, ex, ey)
            for b in curves: bezier(b)
            if not curves and (x != ex or y != ey): line(ex, ey)
            x, y, ctrl = ex, ey, None
        elif cmd in 'Zz':
            result.append('p.CloseFigure();'); x, y = startx, starty; ctrl = None; cmd = ''
        else: raise ValueError((cmd, tokens[i:]))
    return '\n        '.join(result)


